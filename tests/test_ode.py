"""Unit tests for co2gaps.ode: solver verification and calibration on synthetic data."""

import numpy as np
import pandas as pd
import pytest

from co2gaps import baselines, gaps, ode

TZ = "Australia/Melbourne"
START = pd.Timestamp("2024-03-04 00:00", tz=TZ)          # a Monday
LAM, C_OUT = 0.25, 430.0


def _error(method, h, t_end=12.0, s=40.0):
    """Max error against the exact solution for constant S, step h hours."""
    hours = np.arange(0.0, t_end + 1e-12, h)
    exact = ode.exact_constant_source(600.0, hours, LAM, C_OUT, s)
    numeric = ode.simulate(600.0, hours, LAM, C_OUT, np.full(len(hours), s), method)
    return np.max(np.abs(numeric - exact))


@pytest.mark.parametrize("method, order", [("euler", 1), ("rk4", 4)])
def test_solver_convergence_order(method, order):
    """Halving the step cuts the error by 2^order: about 2 for Euler, 16 for RK4."""
    ratio = _error(method, 0.5) / _error(method, 0.25)
    assert ratio == pytest.approx(2.0 ** order, rel=0.15)


def test_rk4_is_accurate_at_the_project_step():
    """At h = 10 min RK4 is far more accurate than the sensor's 1 ppm resolution."""
    assert _error("rk4", 1 / 6) < 1e-4
    assert _error("euler", 1 / 6) < 5.0


def test_euler_is_unstable_when_lambda_h_exceeds_2():
    """Euler's amplification factor is 1 − λh, so λh > 2 makes errors grow (Week 7.3)."""
    hours = np.arange(0.0, 40.0, 10.0)                  # h = 10 h, λh = 2.5
    c = ode.simulate(600.0, hours, LAM, C_OUT, np.zeros(len(hours)), "euler")
    deviation = np.abs(c - C_OUT)
    assert (np.diff(deviation) > 0).all()


def test_simulate_rejects_unknown_method():
    """A misspelt solver name gives a clear error."""
    with pytest.raises(ValueError, match="Unknown method"):
        ode.simulate(500.0, np.array([0.0, 1.0]), LAM, C_OUT, np.zeros(2), "rk2")


def _synthetic_days(days=21):
    """CO₂ from the ODE itself: S = 60 ppm/h on weekdays 09:00–17:00, otherwise 0."""
    index = pd.date_range(START, periods=days * 144, freq="10min")
    working = (index.dayofweek < 5) & (index.hour >= 9) & (index.hour < 17)
    source = np.where(working, 60.0, 0.0)
    hours = ((index - index[0]) / pd.Timedelta(hours=1)).to_numpy()
    values = ode.simulate(C_OUT, hours, LAM, C_OUT, source, "rk4")
    return pd.Series(values, index=index, name="co2_ppm"), source


def test_calibration_recovers_known_parameters():
    """Least squares on overnight decays recovers λ and C_out used to make the data."""
    series, _ = _synthetic_days()
    fit = ode.calibrate_decay(ode.overnight_segments(series))
    assert fit["lam"] == pytest.approx(LAM, rel=0.02)
    assert fit["c_out"] == pytest.approx(C_OUT, abs=1.0)
    assert fit["n_segments"] == 15                       # nights after the 15 weekdays


def test_source_profile_recovers_occupancy_pattern():
    """Inverting the ODE gives S ≈ 60 ppm/h during working hours and ≈ 0 at night."""
    series, _ = _synthetic_days()
    profile = ode.source_profile(series, LAM, C_OUT)
    wed_noon = pd.DatetimeIndex([START + pd.Timedelta(days=2, hours=12, minutes=30)])
    wed_3am = pd.DatetimeIndex([START + pd.Timedelta(days=2, hours=3)])
    assert profile.predict(wed_noon)[0] == pytest.approx(60.0, abs=3.0)
    assert profile.predict(wed_3am)[0] == pytest.approx(0.0, abs=3.0)


def test_ode_estimator_fills_a_gap_in_ode_generated_data():
    """On data generated by the model itself, the ODE fills a working-day gap closely."""
    series, _ = _synthetic_days()
    profile = ode.source_profile(series, LAM, C_OUT)
    start = START + pd.Timedelta(days=9, hours=8)        # Wednesday of week 2
    known, truth = gaps.hide(series, start, start + pd.Timedelta(hours=10))
    for correct in (True, False):
        estimate = ode.ode_estimator(LAM, C_OUT, profile, end_correction=correct)(known, truth.index)
        assert np.max(np.abs(estimate - truth.to_numpy())) < 8.0


def test_end_correction_meets_the_reading_after_the_gap():
    """With end correction the estimate approaches the first measured value after the gap."""
    series, _ = _synthetic_days()
    biased = baselines.TypicalDay().fit(pd.Series(0.0, index=series.index))  # S = 0: wrong
    start = START + pd.Timedelta(days=9, hours=8)
    known, truth = gaps.hide(series, start, start + pd.Timedelta(hours=10))
    corrected = ode.ode_estimator(LAM, C_OUT, biased, end_correction=True)(known, truth.index)
    forward = ode.ode_estimator(LAM, C_OUT, biased, end_correction=False)(known, truth.index)
    after = known[known.index > truth.index.max()].iloc[0]
    assert abs(corrected[-1] - after) < abs(forward[-1] - after)


def test_make_ode_estimators_returns_both_variants():
    """Calibration plus two estimators, with and without end correction."""
    series, _ = _synthetic_days()
    estimators, calibration = ode.make_ode_estimators(series)
    assert set(estimators) == {"ode", "ode_forward"}
    assert calibration["lam"] == pytest.approx(LAM, rel=0.02)
